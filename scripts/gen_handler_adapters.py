#!/usr/bin/env python3
"""Generate the committed handler adapters (src/unifi_fabric/_generated/adapters/<family>.py).

One module per catalog family (the 13 families plus ``meta``), one adapter per ToolSpec,
named exactly ``spec.name``, from the committed catalog
(src/unifi_fabric/_generated/catalog.json). Each adapter has the contract signature
``async def <name>(request_context, validated_arguments, dependencies)`` and calls the
unchanged wrapper with exactly ``**validated_arguments``.

Usage:
    python scripts/gen_handler_adapters.py --write
    python scripts/gen_handler_adapters.py --check
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

ADAPTER_DIR = ROOT / "src" / "unifi_fabric" / "_generated" / "adapters"

_HEADER = '''"""GENERATED by scripts/gen_handler_adapters.py from the tool catalog; do not edit.

Handler adapters of the ``{family}`` family: each calls the unchanged wrapper of its
public tool with exactly ``**validated_arguments`` and returns its result unchanged.
"""

from __future__ import annotations

from collections.abc import Mapping
from typing import TYPE_CHECKING, Any

from unifi_fabric._adapter_runtime import registered_wrapper

if TYPE_CHECKING:
    from unifi_fabric.contracts import Dependencies, RequestContext

__all__ = [
{names}
]
'''

_ADAPTER = '''

async def {name}(
    request_context: RequestContext,
    validated_arguments: Mapping[str, Any],
    dependencies: Dependencies,
) -> Any:
    """Adapter of ``{name}``."""
    return await registered_wrapper("{name}")(**validated_arguments)
'''

_INIT = '''"""GENERATED by scripts/gen_handler_adapters.py from the tool catalog; do not edit.

One module per catalog family; HandlerRef ``unifi_fabric._generated.adapters.<family>:<name>``.
"""
'''


def render() -> dict[str, str]:
    """``file name -> text`` for every adapter module, from the committed catalog."""
    from unifi_fabric.catalog import load_catalog

    by_family: dict[str, list[str]] = {}
    for spec in load_catalog().tools:
        by_family.setdefault(spec.family, []).append(spec.name)
    files = {"__init__.py": _INIT}
    for family, names in sorted(by_family.items()):
        names = sorted(names)
        text = _HEADER.format(family=family, names="\n".join(f'    "{n}",' for n in names))
        text += "".join(_ADAPTER.format(name=n) for n in names)
        files[f"{family}.py"] = text
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", action="store_true", help="Regenerate the adapters.")
    action.add_argument("--check", action="store_true", help="Fail if any adapter is stale.")
    args = parser.parse_args(argv)
    files = render()
    present = {p.name for p in ADAPTER_DIR.glob("*.py")} if ADAPTER_DIR.is_dir() else set()
    if args.write:
        ADAPTER_DIR.mkdir(parents=True, exist_ok=True)
        for name in present - files.keys():
            (ADAPTER_DIR / name).unlink()
        for name, text in files.items():
            (ADAPTER_DIR / name).write_text(text, encoding="utf-8")
        return 0
    stale = sorted(
        name
        for name in files.keys() | present
        if name not in present
        or name not in files
        or (ADAPTER_DIR / name).read_text(encoding="utf-8") != files[name]
    )
    if stale:
        print(
            "handler adapters are stale, missing or extra ("
            + ", ".join(stale)
            + "); run scripts/gen_handler_adapters.py --write",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
