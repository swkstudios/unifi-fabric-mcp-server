#!/usr/bin/env python3
"""Generate the runtime tool index (src/unifi_fabric/_generated/tool_index.py).

The runtime reads tool families, sub-area modules, firewall-route tools and the tools
governed by the connector write switch from this generated table, so no index depends on
which file a wrapper lives in and no source is parsed at runtime. The source derivation
(:mod:`unifi_fabric.families` ``derive_*``) runs here, at generation time; the family of
each tool comes from the committed typed catalog.

Usage:
    python scripts/gen_tool_index.py --write
    python scripts/gen_tool_index.py --check
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

TARGET = ROOT / "src" / "unifi_fabric" / "_generated" / "tool_index.py"

#: Meta tools that keep a selection family until the S meta-tool selection rule lands.
LEGACY_SELECTION_META = ("list_configured_api_keys",)


def _dict(name: str, doc: str, data: dict[str, str]) -> str:
    lines = [f"#: {doc}", f"{name}: dict[str, str] = {{"]
    lines += [f'    "{k}": "{data[k]}",' for k in sorted(data)]
    return "\n".join(lines + ["}", ""])


def _set(name: str, doc: str, data: frozenset[str]) -> str:
    lines = [f"#: {doc}", f"{name}: frozenset[str] = frozenset("]
    lines += ["    {"] + [f'        "{k}",' for k in sorted(data)] + ["    }"]
    return "\n".join(lines + [")", ""])


def render() -> str:
    from unifi_fabric import families
    from unifi_fabric.catalog import META_FAMILY, load_catalog

    derived = families.derive_family_index()
    overrides = {name: derived[name] for name in LEGACY_SELECTION_META}
    family_index = {
        spec.name: spec.family for spec in load_catalog().tools if spec.family != META_FAMILY
    }
    family_index.update(overrides)
    parts = [
        '"""GENERATED by scripts/gen_tool_index.py; do not edit."""',
        "",
        "from __future__ import annotations",
        "",
        _dict(
            "FAMILY_INDEX",
            "tool -> family, from the typed catalog (selection families).",
            family_index,
        ),
        _dict(
            "SELECTION_FAMILY_OVERRIDES",
            "meta tools that keep their baseline selection family.",
            overrides,
        ),
        _dict(
            "MODULE_INDEX",
            "tool -> the tools module it is defined in or delegates to (sub-area key).",
            families.derive_module_index(),
        ),
        _set(
            "FIREWALL_ROUTE_TOOLS",
            "tools whose call graph names a firewall route.",
            families.derive_firewall_route_tools(),
        ),
        _set(
            "CONNECTOR_WRITE_TOOLS",
            "tools whose call graph checks the connector write switch.",
            families.tools_referencing("CONNECTOR_WRITE_ENV"),
        ),
    ]
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", action="store_true", help="Regenerate the tool index.")
    action.add_argument("--check", action="store_true", help="Fail if the tool index is stale.")
    args = parser.parse_args(argv)
    generated = render()
    if args.write:
        TARGET.write_text(generated, encoding="utf-8")
        return 0
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
    if current != generated:
        print("tool index is stale; run scripts/gen_tool_index.py --write", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
