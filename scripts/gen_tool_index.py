#!/usr/bin/env python3
"""Generate the runtime tool index (src/unifi_fabric/_generated/tool_index.py).

The index holds the policy facts the runtime reads per tool and must not derive at
runtime: the tools governed by the connector write switch. It is derived here, at
generation time, from each registered tool's call graph (:mod:`unifi_fabric._call_graph`),
like the read/write verb audit. Tool families and sub-area modules are not in it: they are
the explicit inventory (:mod:`unifi_fabric.catalog.membership`, public #42 steps 6 and 7).

Usage:
    python scripts/gen_tool_index.py --write
    python scripts/gen_tool_index.py --check
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

TARGET = ROOT / "src" / "unifi_fabric" / "_generated" / "tool_index.py"


def _set(name: str, doc: str, data: frozenset[str]) -> str:
    lines = [f"#: {doc}", f"{name}: frozenset[str] = frozenset("]
    lines += ["    {"] + [f'        "{k}",' for k in sorted(data)] + ["    }"]
    return "\n".join(lines + [")", ""])


def render() -> str:
    from unifi_fabric import _call_graph

    # One parse of the package for the derivation below, released on return.
    with _call_graph.source_derivation():
        connector = _call_graph.tools_referencing("CONNECTOR_WRITE_ENV")
    parts = [
        '"""GENERATED by scripts/gen_tool_index.py; do not edit."""',
        "",
        "from __future__ import annotations",
        "",
        _set(
            "CONNECTOR_WRITE_TOOLS",
            "tools whose call graph checks the connector write switch.",
            connector,
        ),
    ]
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", action="store_true", help="Regenerate the tool index.")
    action.add_argument("--check", action="store_true", help="Fail if the tool index is stale.")
    args = parser.parse_args(argv)
    generated = render()
    if args.write:
        TARGET.write_text(generated, encoding="utf-8")
        return 0
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
    if current != generated:
        print("tool index is stale; run scripts/gen_tool_index.py --write", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
