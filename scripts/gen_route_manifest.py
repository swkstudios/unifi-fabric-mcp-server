#!/usr/bin/env python3
"""Generate the route manifest from hermetic tool request captures."""

from __future__ import annotations

import argparse
import json
import re
import socket
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT), str(ROOT / "src")]

#: Tools whose default call sends no request and whose opt-in argument sends reads: the
#: diagnostic bundle is local by default and runs its allowlisted live probes on request.
OPT_IN_VARIANTS: dict[str, tuple[dict[str, object], ...]] = {
    "get_server_diagnostic_bundle": ({"live_probes": ["hosts", "sites"]},),
    # The default call captures only the recorded ``source`` view; ``recent_series`` is a
    # second route with its own recording (``series`` has none, so it cannot be captured).
    "get_controller_stats": (
        {
            "view": "recent_series",
            "schema": "schema-0001",
            "period": "period-0001",
            "bucket": "bucket-0001",
            "end": 1791773785,
        },
    ),
}


#: Declared selector values the tool refuses before any request (no route to capture):
#: Protect 7.x serves no door-lock lock/close action, only a remote unlock.
REFUSED_SELECTORS = {
    ("set_door_lock_state", "action", "lock"),
    ("set_door_lock_state", "action", "close"),
}


LOCAL_ONLY_TOOLS = frozenset({"list_configured_api_keys", "get_event_stream_status"})


def generate():
    from tests import test_spec_conformance as conformance
    from tests import upstream_harness as harness

    # The same socket guard as the reference drift capture: never contact upstream.
    def forbidden(*args, **kwargs):
        raise RuntimeError("route capture attempted network access")

    connect, connect_ex, lookup = (
        socket.socket.connect,
        socket.socket.connect_ex,
        socket.getaddrinfo,
    )
    socket.socket.connect = socket.socket.connect_ex = socket.getaddrinfo = forbidden
    try:
        tools = {}
        for name in sorted(conformance._tools()):
            rows = set()
            requests = conformance.capture(name)
            # Capture each declared route selector, including alternate actions.
            # Some actions have mutually exclusive companion arguments.
            variants = {
                ("manage_mclag_group", "action", "create"): {"group_id": None},
                ("manage_mclag_group", "action", "delete"): {"group": None},
                ("manage_virtual_network", "action", "create"): {"virtual_network_id": None},
                ("control_packet_capture", "action", "stop"): {
                    "capture_id": "probe-object",
                    "options": None,
                },
                ("export_protect_case", "action", "download"): {
                    "case_id": None,
                    "export_id": "probe-object",
                },
                ("update_protect_device_settings", "device_type", "nvr"): {"device_id": None},
            }
            properties = (conformance._tools()[name].parameters or {}).get("properties", {})
            for selector in ("action", "device_type", "output"):
                for value in properties.get(selector, {}).get("enum", []):
                    if (name, selector, value) in REFUSED_SELECTORS:
                        continue
                    overrides = {selector: value, **variants.get((name, selector, value), {})}
                    requests.extend(conformance.capture(name, overrides))
            # Opt-in arguments that add requests a default call never sends.
            for overrides in OPT_IN_VARIANTS.get(name, ()):
                requests.extend(conformance.capture(name, overrides))
            for request in requests:
                path = request.path.replace(harness.HOST_ID, "{console_id}")
                path = path.replace("probe-object", "{id}")
                path = path.replace("/site/default/", "/site/{site}/").replace(
                    "/s/default/", "/s/{site}/"
                )
                path = re.sub(
                    r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}",
                    "{id}",
                    path,
                )
                path = re.sub(r"(?<=/)[0-9a-fA-F]{24}(?=/|$)", "{id}", path)
                # Values generated by the conformance harness for these path arguments.
                # Context is required: replacing every /1 would also alter fixed routes.
                for pattern, replacement in (
                    (r"(/ptz/(?:preset|patrol)(?:/start)?|/ptz/goto)/1$", r"\1/{slot}"),
                    (r"(/interfaces/ports)/1(/actions)$", r"\1/{port_idx}\2"),
                    (r"(/observability/5g/\{id\}/topology/at)/1$", r"\1/{at}"),
                    (r"(/fingerprint_devices)/1$", r"\1/{source}"),
                    (r"(/wifiman)/192\.0\.2\.50$", r"\1/{client_ip}"),
                    (r"(/assets/\{id\})/probe\.png$", r"\1/{filename}"),
                ):
                    path = re.sub(pattern, replacement, path)

                if "/proxy/" in path:
                    route_class = (
                        "integration"
                        if re.search(r"/proxy/[^/]+/integration(?:/|$)", path)
                        else "internal"
                    )
                elif path.startswith(("/v1/", "/ea/")):
                    route_class = "site-manager"
                else:
                    raise ValueError(f"Unclassified route for {name}: {path}")
                if (
                    name.startswith("fabric_connector_")
                    and not request.resolution
                    and request.method == name.removeprefix("fabric_connector_").upper()
                ):
                    prefix = "/v1/connector/consoles/{console_id}/proxy/{app}"
                    rows.add((request.method, prefix + "/integration/{path}", "integration"))
                    rows.add((request.method, prefix + "/{internal_path}", "internal"))
                else:
                    rows.add((request.method, path, route_class))
            if not rows:
                # Tools that read only this server's own state: the local key configuration
                # and the event-stream compatibility records.
                if name not in LOCAL_ONLY_TOOLS:
                    raise ValueError(f"No requests captured for {name}; classify explicitly")
                tools[name] = [{"method": None, "path": None, "route_class": "local-only"}]
            else:
                tools[name] = [
                    {"method": method, "path": path, "route_class": cls}
                    for method, path, cls in sorted(rows)
                ]
        return {
            "version": 1,
            "baseline": {
                "integration": "AVAILABLE",
                "internal": "AVAILABLE",
                "site-manager": "AVAILABLE",
                "local-only": "AVAILABLE",
            },
            "tools": tools,
        }
    finally:
        socket.socket.connect, socket.socket.connect_ex, socket.getaddrinfo = (
            connect,
            connect_ex,
            lookup,
        )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output-dir", type=Path, default=ROOT / "src/unifi_fabric/generated_api_facts"
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    manifest = generate()
    rows = [
        "  " + json.dumps(name) + ": " + json.dumps(routes)
        for name, routes in manifest["tools"].items()
    ]
    output = (
        '{\n  "version": 1,\n  "baseline": '
        + json.dumps(manifest["baseline"])
        + ',\n  "tools": {\n'
        + ",\n".join(rows)
        + "\n  }\n}\n"
    )
    path = args.output_dir / "route_manifest.json"
    if args.check:
        if not path.exists() or path.read_text() != output:
            raise SystemExit("route manifest is out of date")
    else:
        args.output_dir.mkdir(parents=True, exist_ok=True)
        path.write_text(output)


if __name__ == "__main__":
    main()
