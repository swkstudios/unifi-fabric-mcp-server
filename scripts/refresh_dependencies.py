#!/usr/bin/env python3
"""Refresh, check and audit the seven managed pin files from dependencies/manifest.toml.

One manifest-driven refresh replaces the per-file regeneration recipes that used to live
in each file's header. Every output is resolved by ``uv pip compile`` for the manifest's
target interpreter and platform, in manifest order, and a later output is constrained by
the earlier outputs it names, so a package shared between files has one version and one
hash set. The Homebrew formula is regenerated from the runtime lock by the existing
``scripts/gen_homebrew_resources.py``.

Modes (run from anywhere; paths are relative to the repository root)::

    refresh_dependencies.py --upgrade       newest jointly resolving releases (and backend)
    refresh_dependencies.py                 re-resolve inputs, prefer the current pins
    refresh_dependencies.py --check         regenerate in a scratch tree; exit 1 on any drift
    refresh_dependencies.py --audit         pip-audit every output; exit 1 on a finding/error
    refresh_dependencies.py --cap-report P  write the relaxed-cap report (JSON) to P

``--check`` is deterministic against new upstream releases: uv prefers the versions
already pinned in an output file, so a check re-resolves the inputs without ``--upgrade``
and only fails when an input, the manifest, the constraint chain or a hand edit no longer
matches the committed files. It also verifies the shared-version/hash invariant, the
single backend pin and the target-policy consumers (Dockerfile, check_lock_wheels.sh,
the Homebrew generator).

Advisory floors (``[resolution.advisory_floor]``) cover advisories pip-audit does not
report yet: a refresh lifts any pin below its floor with ``uv --upgrade-package`` (only
that package moves), and ``--check`` and every refresh fail while a managed file pins a
version below a floor.

Network: resolution, the Homebrew generator and the audit query PyPI.
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import textwrap
import tomllib
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = Path("dependencies/manifest.toml")
PRIVATE_MANIFEST = Path("dependencies/manifest.private.toml")
BUILD_IN = Path("requirements-build.in")
PYPROJECT = Path("pyproject.toml")
HOMEBREW_GENERATOR = Path("scripts/gen_homebrew_resources.py")
WHEEL_CHECK = Path("scripts/check_lock_wheels.sh")
DOCKERFILE = Path("Dockerfile")

GENERATED_MARK = "# Generated by scripts/refresh_dependencies.py from dependencies/manifest.toml."

_PIN_RE = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)(?:\[[^\]]*\])?==([^\s\\;]+)")
_REQ_NAME_RE = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)")
_RELEASE_RE = re.compile(r"(?:\d+!)?(\d+(?:\.\d+)*)")
_PRE_RE = re.compile(r"[-_.]?(?:a|b|c|rc|alpha|beta|pre|preview|dev)", re.IGNORECASE)


@dataclass(frozen=True)
class Output:
    path: Path
    purpose: str
    inputs: tuple[Path, ...]
    constraints: tuple[Path, ...]
    options: tuple[str, ...]


@dataclass(frozen=True)
class Manifest:
    target: dict
    resolution: dict
    backend_name: str
    backend_version: str
    outputs: tuple[Output, ...]


def load_manifest(root: Path = ROOT) -> Manifest:
    data = tomllib.loads((root / MANIFEST).read_text())
    items = list(data["output"])
    if (root / PRIVATE_MANIFEST).exists():
        items += tomllib.loads((root / PRIVATE_MANIFEST).read_text())["output"]
    for item in items:
        if not (root / item["path"]).exists():
            raise ValueError(f"manifest output {item['path']} does not exist")
    outputs = tuple(
        Output(
            path=Path(item["path"]),
            purpose=item["purpose"],
            inputs=tuple(Path(p) for p in item["inputs"]),
            constraints=tuple(Path(p) for p in item.get("constraints", [])),
            options=tuple(item.get("options", [])),
        )
        for item in items
    )
    order = [o.path for o in outputs]
    for index, output in enumerate(outputs):
        for constraint in output.constraints:
            if constraint not in order[:index]:
                raise ValueError(
                    f"{output.path}: constraint {constraint} is not an earlier manifest output"
                )
    return Manifest(
        target=data["target"],
        resolution=data["resolution"],
        backend_name=data["backend"]["name"],
        backend_version=data["backend"]["version"],
        outputs=outputs,
    )


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def parse_pins(text: str) -> dict[str, tuple[str, frozenset[str]]]:
    """name -> (version, hashes) for every pin of a hash-locked requirements file."""
    pins: dict[str, tuple[str, set[str]]] = {}
    current: str | None = None
    for line in text.splitlines():
        match = _PIN_RE.match(line)
        if match:
            current = normalize(match.group(1))
            pins[current] = (match.group(2), set())
            continue
        if current and "--hash=sha256:" in line:
            pins[current][1].add(line.strip().split("--hash=")[1].split()[0])
        elif line and not line.startswith((" ", "\t")):
            current = None
    return {name: (version, frozenset(hashes)) for name, (version, hashes) in pins.items()}


def release_key(version: str) -> tuple[tuple[int, ...], int]:
    """Order key for a pinned version: the release number, then pre-release below final."""
    match = _RELEASE_RE.match(version)
    if not match:
        raise ValueError(f"cannot order version {version!r}")
    parts = [int(part) for part in match.group(1).split(".")]
    while len(parts) > 1 and parts[-1] == 0:
        parts.pop()
    pre = bool(_PRE_RE.match(version[match.end() :]))
    return tuple(parts), 0 if pre else 1


def advisory_floors(manifest: Manifest) -> dict[str, tuple[str, tuple[str, ...]]]:
    """package -> (first fixed version, advisory ids) from [resolution.advisory_floor]."""
    floors: dict[str, tuple[str, tuple[str, ...]]] = {}
    for name, entry in manifest.resolution.get("advisory_floor", {}).items():
        version, advisories = str(entry.get("version", "")), tuple(entry.get("advisories", ()))
        if not version or not advisories:
            raise ValueError(f"advisory_floor.{name} needs a version and its advisory ids")
        release_key(version)
        floors[normalize(name)] = (version, advisories)
    return floors


def below_floor(manifest: Manifest, text: str) -> dict[str, str]:
    """package -> pinned version for every pin in ``text`` below its advisory floor."""
    floors = advisory_floors(manifest)
    return {
        name: version
        for name, (version, _) in parse_pins(text).items()
        if name in floors and release_key(version) < release_key(floors[name][0])
    }


def advisory_problems(manifest: Manifest, texts: dict[Path, str]) -> list[str]:
    """No managed file pins a package below its advisory floor."""
    floors = advisory_floors(manifest)
    return [
        f"{path}: {name}=={version} is below the advisory floor {floors[name][0]} "
        f"({', '.join(floors[name][1])}): allow the fixed release in "
        "[resolution.exclude_newer_package] and refresh"
        for path, text in texts.items()
        for name, version in sorted(below_floor(manifest, text).items())
    ]


def header(output: Output) -> str:
    lines = textwrap.wrap(output.purpose, width=86, initial_indent="# ", subsequent_indent="# ")
    lines.append(GENERATED_MARK)
    lines.append(
        "# Refresh: python3 scripts/refresh_dependencies.py --upgrade (never edit by hand)."
    )
    return "\n".join(lines) + "\n"


def uv_command() -> list[str]:
    uv = os.environ.get("UV") or shutil.which("uv")
    if not uv:
        raise SystemExit("uv not found: install it from .github/install-tooling-requirements.txt")
    return [uv]


def uv_env() -> dict[str, str]:
    """Resolve from the manifest's index only: an allowlisted environment, no uv config."""
    allowed = {"PATH", "HOME", "TMPDIR", "TEMP", "TMP", "LANG", "LC_ALL", "UV_CACHE_DIR"}
    allowed_prefixes = (
        "SSL_CERT_",
        "REQUESTS_CA_BUNDLE",
        "HTTP_PROXY",
        "HTTPS_PROXY",
        "NO_PROXY",
        "http_proxy",
        "https_proxy",
        "no_proxy",
    )
    env = {
        key: value
        for key, value in os.environ.items()
        if key in allowed or key.startswith(allowed_prefixes)
    }
    env["UV_NO_CONFIG"] = "1"
    return env


def resolution_args(manifest: Manifest) -> list[str]:
    """Index, cooldown cutoff, target and no source builds for every uv resolution."""
    target, resolution = manifest.target, manifest.resolution
    return [
        "--index-url",
        str(resolution["index_url"]),
        "--exclude-newer",
        str(resolution["exclude_newer"]),
        "--no-build",
        *(
            arg
            for name, cutoff in sorted(resolution.get("exclude_newer_package", {}).items())
            for arg in ("--exclude-newer-package", f"{name}={cutoff}")
        ),
        "--python-version",
        str(target["python"]),
        "--python-platform",
        str(target["resolve_platform"]),
    ]


def compile_output(tree: Path, manifest: Manifest, output: Output, upgrade: bool) -> None:
    """Resolve one output inside ``tree`` (a copy of the repository's inputs and outputs)."""
    cmd = [
        *uv_command(),
        "pip",
        "compile",
        "--quiet",
        "--no-header",
        "--generate-hashes",
        "--allow-unsafe",
        *resolution_args(manifest),
        *output.options,
        "--output-file",
        str(output.path),
    ]
    if upgrade:
        cmd.append("--upgrade")
    else:
        # uv keeps an existing pin unless told otherwise: lift only the pins below a floor.
        existing = tree / output.path
        pinned = existing.read_text() if existing.exists() else ""
        for name in sorted(below_floor(manifest, pinned)):
            cmd += ["--upgrade-package", name]
    for constraint in output.constraints:
        cmd += ["--constraint", str(constraint)]
    cmd += [str(p) for p in output.inputs]
    proc = subprocess.run(cmd, cwd=tree, env=uv_env(), capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout + proc.stderr)
        raise SystemExit(f"uv pip compile failed for {output.path}")
    body = (tree / output.path).read_text()
    body = "".join(
        line for line in body.splitlines(keepends=True) if not line.startswith("#")
    ).lstrip("\n")
    (tree / output.path).write_text(header(output) + body)


def cooldown_cutoff(days: int, now: datetime | None = None) -> str:
    moment = (now or datetime.now(UTC)) - timedelta(days=days)
    return moment.replace(minute=0, second=0, microsecond=0).strftime("%Y-%m-%dT%H:%M:%SZ")


def latest_version(name: str, cutoff: str) -> str:
    """Newest final release of ``name`` with every file uploaded before ``cutoff``."""
    import urllib.request

    url = f"https://pypi.org/pypi/{name}/json"
    with urllib.request.urlopen(url) as response:  # noqa: S310 - fixed https PyPI URL
        releases = json.load(response)["releases"]
    eligible = []
    for version, files in releases.items():
        live = [f for f in files if not f.get("yanked")]
        if not live or not re.fullmatch(r"\d+(\.\d+)*", version):
            continue
        if all(f["upload_time_iso_8601"].replace(".000000", "") < cutoff for f in live):
            eligible.append(tuple(int(part) for part in version.split(".")))
    if not eligible:
        raise SystemExit(f"no release of {name} older than {cutoff}")
    return ".".join(str(part) for part in max(eligible))


def set_cutoff(tree: Path, cutoff: str) -> None:
    text = (tree / MANIFEST).read_text()
    text, count = re.subn(r'(?m)^exclude_newer = "[^"]*"$', f'exclude_newer = "{cutoff}"', text)
    if count != 1:
        raise SystemExit("dependencies/manifest.toml must set exclude_newer exactly once")
    (tree / MANIFEST).write_text(text)


def render_backend(tree: Path, manifest: Manifest, version: str) -> None:
    """Write the backend pin into requirements-build.in and pyproject.toml's dev extra."""
    name = manifest.backend_name
    (tree / BUILD_IN).write_text(
        "# Build backend input, rendered by scripts/refresh_dependencies.py from the [backend]\n"
        "# table of dependencies/manifest.toml; edit the manifest, not this file.\n"
        f"{name}=={version}\n"
    )
    pyproject = (tree / PYPROJECT).read_text()
    updated, count = re.subn(rf'"{re.escape(name)}==[^"]+"', f'"{name}=={version}"', pyproject)
    if count != 1:
        raise SystemExit(f"pyproject.toml must pin {name} exactly once in the dev extra")
    (tree / PYPROJECT).write_text(updated)
    manifest_text = (tree / MANIFEST).read_text()
    manifest_text = re.sub(
        r'(\[backend\][^\[]*?version = ")[^"]+(")',
        rf"\g<1>{version}\g<2>",
        manifest_text,
        count=1,
        flags=re.S,
    )
    (tree / MANIFEST).write_text(manifest_text)


def tracked_paths(manifest: Manifest) -> list[Path]:
    paths = {MANIFEST, BUILD_IN, PYPROJECT}
    if (ROOT / PRIVATE_MANIFEST).exists():
        paths.add(PRIVATE_MANIFEST)
    for output in manifest.outputs:
        paths.add(output.path)
        paths.update(output.inputs)
    return sorted(paths)


def build_tree(manifest: Manifest, upgrade: bool, root: Path = ROOT) -> Path:
    tree = Path(tempfile.mkdtemp(prefix="refresh-deps-"))
    for rel in tracked_paths(manifest):
        (tree / rel).parent.mkdir(parents=True, exist_ok=True)
        if (root / rel).exists():
            shutil.copy2(root / rel, tree / rel)
    try:
        version = manifest.backend_version
        if upgrade:
            cutoff = cooldown_cutoff(int(manifest.resolution["cooldown_days"]))
            set_cutoff(tree, cutoff)
            manifest = load_manifest(tree)
            version = latest_version(manifest.backend_name, cutoff)
        render_backend(tree, manifest, version)
        for output in manifest.outputs:
            compile_output(tree, manifest, output, upgrade)
    except BaseException:
        shutil.rmtree(tree, ignore_errors=True)
        raise
    return tree


def shared_pin_problems(texts: dict[Path, str]) -> list[str]:
    """Every package pinned in more than one output has one version and one hash set."""
    seen: dict[str, tuple[Path, str, frozenset[str]]] = {}
    problems: list[str] = []
    for path, text in texts.items():
        for name, (version, hashes) in parse_pins(text).items():
            if not hashes:
                problems.append(f"{path}: {name}=={version} has no --hash")
            if name not in seen:
                seen[name] = (path, version, hashes)
                continue
            first_path, first_version, first_hashes = seen[name]
            if version != first_version:
                problems.append(
                    f"{name}: {first_path} pins {first_version} but {path} pins {version}"
                )
            elif hashes != first_hashes:
                problems.append(f"{name}=={version}: hash sets differ in {first_path} and {path}")
    return problems


def backend_problems(manifest: Manifest, root: Path = ROOT) -> list[str]:
    name, version = manifest.backend_name, manifest.backend_version
    problems = []
    build_in = (root / BUILD_IN).read_text()
    if f"{name}=={version}" not in build_in.splitlines():
        problems.append(f"{BUILD_IN} does not pin {name}=={version} from the manifest")
    pyproject = tomllib.loads((root / PYPROJECT).read_text())
    dev = pyproject["project"]["optional-dependencies"]["dev"]
    if f"{name}=={version}" not in dev:
        problems.append(f"pyproject.toml dev extra does not pin {name}=={version}")
    for output in manifest.outputs:
        pins = parse_pins((root / output.path).read_text())
        if name in pins and pins[name][0] != version:
            problems.append(f"{output.path} pins {name}=={pins[name][0]}, manifest {version}")
    return problems


def target_problems(manifest: Manifest, root: Path = ROOT) -> list[str]:
    """The consumers of the target policy say what the manifest says."""
    target = manifest.target
    problems = []
    dockerfile = (root / DOCKERFILE).read_text()
    if f"PYTHON_IMAGE={target['docker_base']}@" not in dockerfile:
        problems.append(f"Dockerfile PYTHON_IMAGE is not {target['docker_base']}@<digest>")
    wheel_check = (root / WHEEL_CHECK).read_text()
    expected = {
        "architectures": f"for arch in {' '.join(target['image_architectures'])}; do",
        "manylinux range": f"$(seq {target['manylinux_min']} {target['manylinux_max']})",
        "python version": f"--python-version {target['python']}",
        "implementation": f"--implementation {target['implementation']}",
        "abi": f"--abi {target['abi']}",
    }
    for what, needle in expected.items():
        if needle not in wheel_check:
            problems.append(f"{WHEEL_CHECK}: {what} does not match the manifest ({needle!r})")
    for workflow in target.get("python_workflows", []):
        workflow_text = (root / workflow).read_text()
        versions = set(re.findall(r"python-version: ['\"]?([0-9.]+)['\"]?", workflow_text))
        version_files = re.findall(
            r"(?m)^ *python-version-file: *['\"]?([^'\"\s#]+)['\"]? *(?:#.*)?$",
            workflow_text,
        )
        for version_file in version_files:
            try:
                versions.add((root / version_file).read_text().strip())
            except (OSError, UnicodeError) as exc:
                problems.append(
                    f"{workflow}: cannot read python-version-file {version_file}: {exc}"
                )
        if versions != {str(target["python"])}:
            problems.append(
                f"{workflow}: setup-python {sorted(versions)} is not {target['python']}"
            )
    generator = (root / HOMEBREW_GENERATOR).read_text()
    if f'("{target["homebrew_python"]}", None)' not in generator:
        problems.append(f"{HOMEBREW_GENERATOR}: DEPENDS_ON lacks {target['homebrew_python']}")
    return problems


def generated_problems(manifest: Manifest, root: Path = ROOT) -> list[str]:
    return [
        f"{output.path}: missing the generated-file mark"
        for output in manifest.outputs
        if GENERATED_MARK not in (root / output.path).read_text()
    ]


def homebrew(root: Path, check: bool) -> int:
    cmd = [sys.executable, str(HOMEBREW_GENERATOR)]
    if check:
        cmd.append("--check")
    return subprocess.run(cmd, cwd=root, check=False).returncode


def run_check(manifest: Manifest) -> int:
    problems: list[str] = []
    tree = build_tree(manifest, upgrade=False)
    try:
        for rel in [*(o.path for o in manifest.outputs), BUILD_IN, PYPROJECT, MANIFEST]:
            current = (ROOT / rel).read_text() if (ROOT / rel).exists() else ""
            fresh = (tree / rel).read_text()
            if current != fresh:
                diff = difflib.unified_diff(
                    current.splitlines(keepends=True),
                    fresh.splitlines(keepends=True),
                    f"a/{rel}",
                    f"b/{rel}",
                )
                sys.stdout.writelines(diff)
                problems.append(f"{rel} is stale: run scripts/refresh_dependencies.py")
    finally:
        shutil.rmtree(tree, ignore_errors=True)
    texts = {o.path: (ROOT / o.path).read_text() for o in manifest.outputs}
    problems += shared_pin_problems(texts)
    problems += advisory_problems(manifest, texts)
    problems += backend_problems(manifest)
    problems += target_problems(manifest)
    problems += generated_problems(manifest)
    if homebrew(ROOT, check=True) != 0:
        problems.append("Homebrew formula is stale: run scripts/gen_homebrew_resources.py")
    for problem in problems:
        print(f"refresh --check: {problem}", file=sys.stderr)
    if not problems:
        count = len(manifest.outputs)
        print(f"refresh --check: {count} managed files, backend, target and formula current")
    return 1 if problems else 0


def run_refresh(manifest: Manifest, upgrade: bool) -> int:
    tree = build_tree(manifest, upgrade=upgrade)
    try:
        for rel in [*(o.path for o in manifest.outputs), BUILD_IN, PYPROJECT, MANIFEST]:
            shutil.copy2(tree / rel, ROOT / rel)
    finally:
        shutil.rmtree(tree, ignore_errors=True)
    rc = homebrew(ROOT, check=False)
    manifest = load_manifest()
    texts = {o.path: (ROOT / o.path).read_text() for o in manifest.outputs}
    problems = (
        shared_pin_problems(texts) + advisory_problems(manifest, texts) + backend_problems(manifest)
    )
    for problem in problems:
        print(f"refresh: {problem}", file=sys.stderr)
    return 1 if problems or rc else 0


def run_audit(manifest: Manifest) -> int:
    pip_audit = os.environ.get("PIP_AUDIT") or shutil.which("pip-audit")
    cmd = [pip_audit] if pip_audit else [sys.executable, "-m", "pip_audit"]
    failed = []
    for output in manifest.outputs:
        print(f"pip-audit: {output.path}", flush=True)
        proc = subprocess.run(
            [
                *cmd,
                "--requirement",
                str(output.path),
                "--require-hashes",
                "--disable-pip",
                "--strict",
                "--progress-spinner",
                "off",
            ],
            cwd=ROOT,
            check=False,
        )
        if proc.returncode != 0:
            failed.append(str(output.path))
    if failed:
        print(f"pip-audit failed (vulnerability or error): {', '.join(failed)}", file=sys.stderr)
        return 1
    print(f"pip-audit: no known vulnerabilities in {len(manifest.outputs)} managed files")
    return 0


def relax(spec: str) -> str:
    """Drop upper bounds and turn exact/compatible pins into lower bounds."""
    requirement, _, marker = spec.partition(";")
    match = re.match(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*(?:\[[^\]]*\])?)\s*(.*)$", requirement)
    if not match:
        return spec
    name, specifiers = match.groups()
    kept = []
    for item in filter(None, (s.strip() for s in specifiers.split(","))):
        if item.startswith(("<", "<=")):
            continue
        if item.startswith(("==", "~=")):
            item = ">=" + item[2:].strip().rstrip(".*")
        kept.append(item)
    relaxed = name + ",".join(kept)
    return f"{relaxed};{marker}" if marker else relaxed


def requirement_name(spec: str) -> str:
    match = _REQ_NAME_RE.match(spec)
    if not match:
        raise ValueError(f"unparseable requirement: {spec!r}")
    return normalize(match.group(1))


def capped(spec: str) -> bool:
    requirement = spec.partition(";")[0]
    return bool(re.search(r"(<|==|~=)", requirement))


def run_cap_report(manifest: Manifest, report: Path) -> int:
    """Resolve the project's direct requirements with caps lifted and compare to the lock."""
    project = tomllib.loads((ROOT / PYPROJECT).read_text())["project"]
    direct = list(project["dependencies"]) + list(project["optional-dependencies"]["dev"])
    caps = {requirement_name(s): s for s in direct if capped(s)}
    locked = parse_pins((ROOT / manifest.outputs[0].path).read_text())
    with tempfile.TemporaryDirectory(prefix="cap-report-") as tmp:
        relaxed_in = Path(tmp) / "relaxed.in"
        relaxed_in.write_text("\n".join(relax(s) for s in direct) + "\n")
        out = Path(tmp) / "relaxed.txt"
        proc = subprocess.run(
            [
                *uv_command(),
                "pip",
                "compile",
                "--quiet",
                "--no-header",
                "--no-annotate",
                *resolution_args(manifest),
                "--output-file",
                str(out),
                str(relaxed_in),
            ],
            env=uv_env(),
            capture_output=True,
            text=True,
            check=False,
        )
        relaxed = parse_pins(out.read_text()) if proc.returncode == 0 else {}
    candidates = [
        {
            "package": name,
            "locked": locked[name][0] if name in locked else None,
            "relaxed": version,
            "cap": caps.get(name),
            # capped: a cap or exact pin in pyproject.toml hides this release; behind: the
            # lock trails the newest release the caps allow (run --upgrade).
            "kind": "capped" if name in caps else "behind",
        }
        for name, (version, _) in sorted(relaxed.items())
        if name not in locked or locked[name][0] != version
    ]
    result = {
        "lock": str(manifest.outputs[0].path),
        "caps": caps,
        "resolution": "ok" if proc.returncode == 0 else "conflict",
        "conflict": None if proc.returncode == 0 else (proc.stderr or proc.stdout).strip(),
        "candidates": candidates,
    }
    report.write_text(json.dumps(result, indent=2) + "\n")
    print(
        f"cap report: {len(caps)} capped direct requirements, "
        f"{len(candidates)} relaxed-cap candidates, resolution {result['resolution']}"
    )
    return 0


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--upgrade", action="store_true", help="Newest jointly resolving releases.")
    mode.add_argument("--check", action="store_true", help="Exit 1 if any output is stale.")
    mode.add_argument("--audit", action="store_true", help="pip-audit every managed file.")
    mode.add_argument("--cap-report", type=Path, metavar="PATH", help="Write the cap report.")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    manifest = load_manifest()
    if args.check:
        return run_check(manifest)
    if args.audit:
        return run_audit(manifest)
    if args.cap_report:
        return run_cap_report(manifest, args.cap_report)
    return run_refresh(manifest, upgrade=args.upgrade)


if __name__ == "__main__":
    sys.exit(main())
