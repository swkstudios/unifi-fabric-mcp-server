#!/usr/bin/env python3
"""Regenerate the Homebrew formula's ``depends_on`` block and ``resource`` stanzas.

The formula installs the same dependency set as the container image: one resource
per package pinned in ``requirements-runtime.lock``, at exactly the locked version, using
that release's source distribution (sdist) URL and sha256 from PyPI. Run this after
any change to ``requirements-runtime.lock``::

    python3 scripts/gen_homebrew_resources.py          # rewrite the formula
    python3 scripts/gen_homebrew_resources.py --check  # show the diff, write nothing

Both modes query the PyPI JSON API for the locked versions.

The ``depends_on`` block is owned by this script too (``DEPENDS_ON`` below), so the
formula's system dependencies cannot drift from what the resources need to build:

- ``pkgconf`` (build): cryptography's Rust extension links OpenSSL through
  ``openssl-sys``, which locates it with pkg-config. Without it the build fails on
  Linuxbrew ("Could not find openssl via pkg-config").
- ``rust`` (build): cryptography ships only an sdist that compiles a Rust extension.
- ``libyaml``: PyYAML builds its C extension against it.
- ``openssl@3``: the OpenSSL cryptography links against.
- ``python@3.12``: the virtualenv interpreter.

The order is the one ``brew audit``/``brew style`` requires: build dependencies
first, then runtime dependencies, each group alphabetical.

``tests/test_homebrew_formula.py`` checks (offline) that the formula's resources
match the lock, so a lock change without a regenerated formula fails CI.

``brew update-python-resources`` is deliberately not used: it resolves the newest
releases from PyPI rather than the locked versions, so the formula drifts from the
tested dependency set.
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "requirements-runtime.lock"
FORMULA = ROOT / "packaging" / "homebrew" / "unifi-fabric-mcp-server.rb"

# (name, tag) in brew-audit order: ``:build`` dependencies first, then runtime ones,
# each group alphabetical. See the module docstring for why each is needed.
DEPENDS_ON: tuple[tuple[str, str | None], ...] = (
    ("pkgconf", "build"),
    ("rust", "build"),
    ("libyaml", None),
    ("openssl@3", None),
    ("python@3.12", None),
)

_DEPENDS_COMMENT = (
    "  # Generated by scripts/gen_homebrew_resources.py (DEPENDS_ON). cryptography\n"
    "  # (pulled in transitively via fastmcp's OAuth stack) ships only an sdist that\n"
    "  # compiles a Rust extension; openssl-sys finds OpenSSL through pkg-config (pkgconf).\n"
    "  # PyYAML builds its C extension against libyaml.\n"
)

_PIN_RE = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)(?:\[[^\]]*\])?==([^\s\\;]+)")


def normalize(name: str) -> str:
    """PEP 503 normalized project name (``jaraco.classes`` -> ``jaraco-classes``)."""
    return re.sub(r"[-_.]+", "-", name).lower()


def locked_pins(lock_text: str) -> dict[str, str]:
    """Map normalized package name -> pinned version for every pin in the lock."""
    pins: dict[str, str] = {}
    for line in lock_text.splitlines():
        match = _PIN_RE.match(line)
        if match:
            pins[normalize(match.group(1))] = match.group(2)
    return pins


def sdist(name: str, version: str) -> tuple[str, str]:
    """Return (url, sha256) of the sdist for ``name==version`` from the PyPI JSON API."""
    api = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(api, timeout=None) as resp:  # noqa: S310 - fixed https host
        data = json.load(resp)
    for artifact in data["urls"]:
        if artifact["packagetype"] == "sdist":
            return artifact["url"], artifact["digests"]["sha256"]
    raise SystemExit(f"{name}=={version}: no sdist published on PyPI")


def render(pins: dict[str, str]) -> str:
    blocks = []
    for name in sorted(pins):
        url, sha = sdist(name, pins[name])
        blocks.append(f'  resource "{name}" do\n    url "{url}"\n    sha256 "{sha}"\n  end\n')
    return "".join(blocks)


def render_depends_on() -> str:
    lines = []
    for name, tag in DEPENDS_ON:
        suffix = f" => :{tag}" if tag else ""
        lines.append(f'  depends_on "{name}"{suffix}\n')
    return _DEPENDS_COMMENT + "".join(lines)


def regenerate(formula: str, pins: dict[str, str]) -> str:
    """Return ``formula`` with its ``depends_on`` block and resource block regenerated.

    The ``depends_on`` block is everything between the ``license`` line and the first
    ``resource`` stanza; the resource block runs from there to ``def install``.
    """
    license_at = formula.index("\n  license ")
    deps_start = formula.index("\n", license_at + 1) + 1
    formula.index('  resource "')  # raises if the formula has no resource block
    end = formula.index("  def install")
    return (
        formula[:deps_start]
        + "\n"
        + render_depends_on()
        + "\n"
        + render(pins)
        + "\n"
        + formula[end:]
    )


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Regenerate the Homebrew formula resources from requirements-runtime.lock "
        "(locked versions, PyPI sdist URL and sha256)."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Do not write: print a diff of what would change and exit 1 if the formula "
        "is out of date (0 if it is current).",
    )
    parser.add_argument("--lock", type=Path, default=LOCK, help="Lock file to read.")
    parser.add_argument("--formula", type=Path, default=FORMULA, help="Formula file to update.")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    pins = locked_pins(args.lock.read_text())
    current = args.formula.read_text()
    updated = regenerate(current, pins)
    if args.check:
        if updated == current:
            print(f"{args.formula.name}: {len(pins)} resources match {args.lock.name}")
            return 0
        sys.stdout.writelines(
            difflib.unified_diff(
                current.splitlines(keepends=True),
                updated.splitlines(keepends=True),
                fromfile=f"{args.formula.name} (current)",
                tofile=f"{args.formula.name} (from {args.lock.name})",
            )
        )
        return 1
    args.formula.write_text(updated)
    print(f"wrote {len(pins)} resources to {args.formula}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
