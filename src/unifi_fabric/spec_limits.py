"""Spec value limits, enforced before any request.

Every ``minimum`` / ``maximum`` / ``exclusiveMinimum`` / ``exclusiveMaximum`` /
``minLength`` / ``maxLength`` / ``pattern`` / ``enum`` / ``minItems`` / ``maxItems`` the
vendored OpenAPI specs state for a value a tool argument carries is in
:data:`._spec_limits_table.SPEC_LIMITS` (generated by ``tests/spec_limits_gen.py``, which
maps each limit to the argument by tracing where the argument's value lands in the
request), plus the few limits a spec states only in prose (patrol slot 0-4, preset slot
>= -1, output channel 0 or 1). :class:`SpecLimitMiddleware` checks the arguments of every
call against it before the tool body runs, so a value the API would reject fails with no
request at all, naming the argument, the limit and the spec keyword.

Exactly the spec's limits, never stricter:

* a keyword only constrains values of its own JSON type (numbers for the numeric bounds,
  strings for lengths and ``pattern``, arrays for item counts), as in JSON Schema; a
  value of another type is left to the argument's own type check;
* integer schemas with decimal-string enums accept the listed strings and their integer
  equivalents (the upstream schema's type/enum mismatch), without changing the request;
* string lengths count characters (code points), the JSON Schema unit;
* ``null`` / an omitted argument is never checked (the spec's nullability is the API's);
* inside an object body, additive ``_`` keys and the redaction mask (never sent) are
  skipped, and a field the request schema does not constrain is not checked;
* ``anyOf`` / ``oneOf`` alternatives: a value fails only when it fails every alternative;
  an alternative carries its JSON ``type`` (the table's only ``type`` keyword), so a value
  of another type fails that alternative;
* ``pattern`` follows ECMA-262 anchoring: a trailing ``$`` matches only at the very end
  (Python's ``$`` would also accept a trailing newline).

Error messages name lengths, not string contents, for length limits (a password argument
is never echoed).
"""

from __future__ import annotations

import math
import re
from functools import cache
from typing import Any

from fastmcp.exceptions import ToolError
from fastmcp.server.middleware import CallNext, Middleware, MiddlewareContext

from .argument_errors import echoed_input, input_path_component
from .generated_api_facts._spec_limits_table import SPEC_LIMITS
from .redaction import REDACTION_MASK, write_redaction_enabled

_INTEGER_STRING = re.compile(r"-?[0-9]+")


def _is_number(value: Any) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


_JSON_TYPES: dict[str, Any] = {
    "string": lambda v: isinstance(v, str),
    "array": lambda v: isinstance(v, list),
    "object": lambda v: isinstance(v, dict),
    "boolean": lambda v: isinstance(v, bool),
    "integer": lambda v: isinstance(v, int) and not isinstance(v, bool),
    "number": _is_number,
}


def _has_json_type(value: Any, expected: str) -> bool:
    """True when ``value`` is of the JSON Schema type ``expected`` (unknown names pass)."""
    check = _JSON_TYPES.get(expected)
    return True if check is None else bool(check(value))


def _same(value: Any, allowed: Any) -> bool:
    """Type-strict equality (``True`` never equals ``1``; ``1`` equals ``1.0``)."""
    if isinstance(value, bool) or isinstance(allowed, bool):
        return isinstance(value, bool) and isinstance(allowed, bool) and value is allowed
    if _is_number(value) and _is_number(allowed):
        return bool(value == allowed)
    return type(value) is type(allowed) and bool(value == allowed)


def _ecma(pattern: str) -> str:
    """ECMA-262 anchoring: a trailing ``$`` matches only at the very end (``\\Z``)."""
    if pattern.endswith("$") and not pattern.endswith("\\$"):
        return pattern[:-1] + r"\Z"
    return pattern


def _table_patterns(node: Any) -> list[str]:
    if isinstance(node, dict):
        own = [node["pattern"]] if isinstance(node.get("pattern"), str) else []
        return own + [p for value in node.values() for p in _table_patterns(value)]
    if isinstance(node, list):
        return [p for value in node for p in _table_patterns(value)]
    return []


#: Every ``pattern`` of the table, compiled once at import (and so linted with the module
#: globals by tests/test_redos_lint.py).
SPEC_PATTERNS: dict[str, re.Pattern[str]] = {
    p: re.compile(_ecma(p)) for p in sorted(set(_table_patterns(SPEC_LIMITS)))
}


def _compiled(pattern: str) -> re.Pattern[str]:
    return SPEC_PATTERNS.get(pattern) or _compile_other(pattern)


@cache
def _compile_other(pattern: str) -> re.Pattern[str]:
    """A pattern outside the table (a direct caller's own fragment)."""
    return re.compile(_ecma(pattern))


def _describe(value: Any) -> str:
    if isinstance(value, str):
        return f"a string of {len(value)} characters"
    if isinstance(value, list):
        return f"a list of {len(value)} items"
    return repr(value)


def limit_problems(value: Any, limits: dict[str, Any], where: str) -> list[str]:
    """Every way ``value`` breaks ``limits`` (one fragment of the table), as messages."""
    if value is None or (
        write_redaction_enabled() and isinstance(value, str) and value == REDACTION_MASK
    ):
        return []
    if "anyOf" in limits:
        branches = [limit_problems(value, alt, where) for alt in limits["anyOf"]]
        if all(branches):
            return [
                f"{where} matches none of the allowed forms: "
                + " | ".join("; ".join(b) for b in branches)
            ]
    problems: list[str] = []
    shown: str | None = None
    expected = limits.get("type")
    if isinstance(expected, str) and not _has_json_type(value, expected):
        return [f"{where} is not of type {expected} (spec type)"]
    if limits.get("integerString") and isinstance(value, str):
        if not _INTEGER_STRING.fullmatch(value):
            return [
                f"{where} is {echoed_input(value)}: must be a decimal integer "
                "(the spec type is integer)"
            ]
        try:
            value = int(value)
        except ValueError:
            # Past the interpreter's int digit limit (thousands of digits): beyond every
            # spec bound, so it is compared by sign, and echoed as the caller sent it.
            shown = echoed_input(value)
            value = -math.inf if value.startswith("-") else math.inf
    if _is_number(value):
        for key, ok, text in (
            ("minimum", lambda v, b: v >= b, ">="),
            ("maximum", lambda v, b: v <= b, "<="),
            ("exclusiveMinimum", lambda v, b: v > b, ">"),
            ("exclusiveMaximum", lambda v, b: v < b, "<"),
        ):
            if key in limits and not ok(value, limits[key]):
                bound = limits[key]
                problems.append(
                    f"{where} is {shown or echoed_input(value)}: must be {text} {bound} "
                    f"(spec {key} {bound})"
                )
    if isinstance(value, str):
        n, low, high = len(value), limits.get("minLength"), limits.get("maxLength")
        if (low is not None and n < low) or (high is not None and n > high):
            if low is not None and high is not None:
                rule, keys = f"{low}-{high} characters", f"minLength {low}, maxLength {high}"
            elif low is not None:
                rule, keys = f"at least {low} characters", f"minLength {low}"
            else:
                rule, keys = f"at most {high} characters", f"maxLength {high}"
            problems.append(f"{where} is {_describe(value)}: must be {rule} (spec {keys})")
        if "pattern" in limits and not _compiled(limits["pattern"]).search(value):
            problems.append(
                f"{where} is {echoed_input(value)}: must match the pattern "
                f"{limits['pattern']!r} (spec pattern)"
            )
    integer_enum_match = (
        limits.get("integerEnum")
        and isinstance(value, int)
        and not isinstance(value, bool)
        and any(
            isinstance(allowed, str)
            and _INTEGER_STRING.fullmatch(allowed)
            and value == int(allowed)
            for allowed in limits.get("enum", [])
        )
    )
    if (
        "enum" in limits
        and not integer_enum_match
        and not any(_same(value, allowed) for allowed in limits["enum"])
    ):
        choices = ", ".join(repr(v) for v in limits["enum"])
        problems.append(
            f"{where} is {shown or echoed_input(value)}: must be one of {choices} (spec enum)"
        )
    if isinstance(value, list):
        n = len(value)
        if "minItems" in limits and n < limits["minItems"]:
            problems.append(
                f"{where} is {_describe(value)}: must have at least {limits['minItems']} "
                f"item(s) (spec minItems {limits['minItems']})"
            )
        if "maxItems" in limits and n > limits["maxItems"]:
            problems.append(
                f"{where} is {_describe(value)}: must have at most {limits['maxItems']} "
                f"item(s) (spec maxItems {limits['maxItems']})"
            )
        if "items" in limits:
            for index, item in enumerate(value):
                problems.extend(limit_problems(item, limits["items"], f"{where}[{index}]"))
    if isinstance(value, dict) and "properties" in limits:
        for key, item in value.items():
            sub = limits["properties"].get(key)
            if sub is not None and not (isinstance(key, str) and key.startswith("_")):
                problems.extend(limit_problems(item, sub, f"{where}.{input_path_component(key)}"))
    return problems


def argument_problems(tool: str, arguments: dict[str, Any]) -> list[str]:
    """Every spec-limit problem in a call's arguments (``[]`` for a tool with no limits)."""
    problems: list[str] = []
    for arg, limits in SPEC_LIMITS.get(tool, {}).items():
        if arg in arguments:
            if arg in {"limit", "page_size", "pageSize"}:
                # Page maxima constrain each wire request, not the requested total.
                limits = {k: v for k, v in limits.items() if k != "maximum"}
            problems.extend(limit_problems(arguments[arg], limits, repr(arg)))
    return problems


def check_arguments(tool: str, arguments: dict[str, Any]) -> None:
    """Raise ``ValueError`` listing every spec-limit problem (for direct callers)."""
    problems = argument_problems(tool, arguments)
    if problems:
        raise ValueError("; ".join(problems))


class SpecLimitMiddleware(Middleware):
    """Refuse a call whose arguments break a spec value limit, before the tool body runs."""

    async def on_call_tool(
        self,
        context: MiddlewareContext[Any],
        call_next: CallNext[Any, Any],
    ) -> Any:
        name = str(getattr(context.message, "name", ""))
        if name in SPEC_LIMITS:
            arguments = getattr(context.message, "arguments", None) or {}
            problems = argument_problems(name, arguments)
            if problems:
                raise ToolError("; ".join(problems))
        return await call_next(context)
