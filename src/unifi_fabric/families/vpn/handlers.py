"""The vpn family's DNS handlers: static DNS records and DoH server names (public #42 layout).

Route: the web app's own v2 collections (no published Network spec has a route for
them): ``static-dns`` with its ``_id`` ids and field names, and
``settings/doh/available-server-names``. The published DNS-policy tools (``*_dns_policy``)
use the Integration route ``/v1/sites/{siteId}/dns/policies`` with its own ids and schema;
they are network tools.

Every response body is passed through verbatim; additions are ``_``-prefixed keys. Under
``dry-run policy`` every write returns the client's dry-run preview and sends nothing.
``registrar.py`` registers these as tools; ``network_vpn_dns`` re-exports them.
"""

